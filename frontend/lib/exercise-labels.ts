/** 单个动作英文名 → 中文名 */
export function exerciseNameCn(name: string): string {
  if (!name) return "—";
  return EXERCISE_CN[name] ?? name;
}

/** 目标肌群英文 → 中文 */
export function muscleCn(name: string): string {
  if (!name) return "—";
  return MUSCLE_CN[name] ?? name;
}

/**
 * 将含英文动作名的句子翻译为中文（用于替代建议等字段）。
 * 例："Goblet Squat or Leg Press" → "高脚杯深蹲 或 腿举"
 */
export function translateExerciseText(text: string): string {
  if (!text) return "—";
  let result = text;
  const sorted = Object.entries(EXERCISE_CN).sort((a, b) => b[0].length - a[0].length);
  for (const [en, cn] of sorted) {
    result = result.split(en).join(cn);
  }
  return result
    .replace(/\bor\b/gi, "或")
    .replace(/\(Light Load\)/gi, "（轻重量）")
    .replace(/\(Light\)/gi, "（轻重量）")
    .replace(/\(Assisted\)/gi, "（辅助）")
    .replace(/\(No Load\)/gi, "（无负重）")
    .replace(/\(Bodyweight\)/gi, "（徒手）")
    .replace(/\(Feet Elevated\)/gi, "（脚垫高）");
}

/** 动作展示组件用的标准格式：中文为主，英文为辅 */
export function formatExerciseName(name: string): { cn: string; en: string; isTranslated: boolean } {
  const cn = exerciseNameCn(name);
  return { cn, en: name, isTranslated: cn !== name };
}
